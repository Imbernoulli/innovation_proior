#!/usr/bin/env python3
"""go-judge REST API shim that needs NO user namespaces. V2: + core pinning.

V2 (timing fidelity, 2026-08-19): identical semantics to gojudge_shim.py plus
OPTIONAL per-run CPU-core pinning for faithful timing under concurrency.
  SHIM_PIN_CORES   -- "" (off, default: byte-identical behavior to v1),
                      or an explicit core list "4-15" / "4,5,8-11".
                      Every sandboxed child (compile, solution, checker,
                      interactor) is pinned via sched_setaffinity to a core
                      group ACQUIRED from this pool for the duration of the
                      run, so concurrent submissions never time-share a core
                      and measured cpu time is contention-free. Cores must be
                      inside the job's cgroup cpuset. Pool acquisition for a
                      request's cmds is atomic (no partial-hold deadlock with
                      interactive pipeMapping pairs).
  SHIM_CORES_PER_RUN -- cores per group (default 1; single-threaded judged
                      code needs exactly 1).
  Run the shim/node/driver processes themselves on DISJOINT cores (taskset
  the starter) so infra never runs on judged cores.

Drop-in replacement for the go-judge binary in the FrontierCS judge stack, for
clusters where unprivileged user namespaces are disabled (della since
2026-07-28: user.max_user_namespaces=0, so go-judge's clone(CLONE_NEWUSER)
dies with ENOSPC). The node judge (Frontier-CS/algorithmic) is not modified at
all -- this server speaks the exact API subset it uses:

    GET    /version          POST /run          DELETE /file/:id
    GET    /file/:id         POST /file (multipart, dead path in practice)

Fidelity notes (matching the go-judge v1.11.1 behavior OBSERVED on this
cluster, where cgroups were unavailable and go-judge already ran in its
rlimit/rusage fallback mode):
  - cpuLimit  -> RLIMIT_CPU (ceil seconds); SIGXCPU or cpu>limit => "Time Limit Exceeded"
  - clockLimit (else 2x cpu) -> wall timer; expiry kills the process group => TLE
  - memoryLimit -> RLIMIT_AS when addressSpaceLimit else RLIMIT_DATA
    (=> MLE surfaces as "Nonzero Exit Status"/"Signalled", same as observed)
  - stackLimit -> RLIMIT_STACK
  - memory reported = rusage ru_maxrss (bytes); runTime/time = cpu ns
  - args[0] with no '/' resolves against the sandbox workdir (NO PATH search)
  - collector files ({"name","max"}) truncate at max; overflow closes the pipe
    (child gets SIGPIPE) and yields "Output Limit Exceeded"
  - copyOut names that are collectors are a silent no-op (compile calls do this)
  - copyOutCached -> opaque fileId, reusable as copyIn {"fileId"} (mode 0755)
  - pipeMapping between two concurrent cmds (interactive problems) via os.pipe()

NOT provided (documented divergence): filesystem/pid/net isolation. Submitted
code runs as the calling user with normal FS access. Use ONLY for code
generated by our own models (same trust level as the bwrap-less research
track), never for adversarial third-party submissions.

Usage: gojudge_shim.py [-http-addr 127.0.0.1:5050] [-dir /tmp/gj-store]
                       [-calibrate-only]
       (unrecognized go-judge flags like -parallelism/-cgroup-prefix are
        accepted and ignored so the starter can pass the same argv)

Timing robustness (2026-08-03):
  SHIM_TLE_RETRY=1 (default ON): single-cmd runs that end TLE with
      cpu < SHIM_TLE_RETRY_FACTOR (1.25) x cpuLimit are rerun once; the retry
      is kept iff it is no longer TLE. Retries logged to stderr.
  Node speed calibration at startup (~1s deterministic loop): ops/sec and the
      factor vs a hardcoded ailab-EPYC reference are printed and exposed in
      GET /version (nodeSpeedCalibration). Measurement only -- no limit scaling.
      `-calibrate-only` prints the calibration JSON and exits (use it on an
      ailab node to re-baseline AILAB_EPYC_REF_OPS_PER_SEC).
"""

