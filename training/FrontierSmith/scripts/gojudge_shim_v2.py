STORE_DIR = None
STORE_LOCK = threading.Lock()
STORE = {}  # fileId -> path

NS = 1_000_000_000

# ---------------------------------------------------------------------------
# Timing robustness (2026-08-03)
# ---------------------------------------------------------------------------
# (a) Borderline-TLE retry. Timing-borderline solutions flip TLE across CPU
# generations (measured: the same FCS code runs 1.44s on an old Xeon vs <1.0s
# limit-passing on an ailab EPYC). Mirror real judges' rerun policy: when a
# SINGLE-cmd run (never interactive pipeMapping pairs) ends "Time Limit
# Exceeded" with cpu_ns < SHIM_TLE_RETRY_FACTOR x cpuLimit, rerun ONCE in a
# fresh workdir and keep the better outcome (retry kept iff it is no longer
# TLE). Retries are logged to stderr. SHIM_TLE_RETRY=0 disables.
SHIM_TLE_RETRY = os.environ.get("SHIM_TLE_RETRY", "1").lower() not in (
    "0", "false", "no", "")
SHIM_TLE_RETRY_FACTOR = float(os.environ.get("SHIM_TLE_RETRY_FACTOR", "1.25"))

# (b) Node speed calibration. A fixed ~1s deterministic CPU loop is timed at
# startup and compared against a hardcoded ailab-EPYC reference so every eval
# log records the node's speed class (factor >1 = faster than reference).
# MEASUREMENT ONLY: limits are NOT scaled by default.
# Reference: della login EPYC 7H12 (Zen2) measures ~3.12e6 ops/s under
# CPython 3.12; ailab EPYC (H200 hosts) is the pinned FCS eval platform --
# re-baseline by running `gojudge_shim.py -calibrate-only` there and pasting
# the printed opsPerSec here. Loop speed depends on the CPython version too,
# so re-baseline if the deploy interpreter changes.
AILAB_EPYC_REF_OPS_PER_SEC = 6.269e6  # ailab H200-host EPYC, measured 2026-08-03 (job 11964225)

NODE_CALIB = {}  # filled by _calibrate_node_speed() in main()


